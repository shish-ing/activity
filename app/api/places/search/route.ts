export async function GET(request: Request) {
  const { searchParams } = new URL(request.url)
  const q = searchParams.get('q')?.trim() ?? ''

  if (!q) {
    return NextResponse.json(JEONJU_PLACES_DATABASE.slice(0, 8))
  }

  const matched = JEONJU_PLACES_DATABASE.filter(
    (p) =>
      p.name.toLowerCase().includes(q.toLowerCase()) ||
      p.category.toLowerCase().includes(q.toLowerCase()) ||
      p.address?.toLowerCase().includes(q.toLowerCase()) ||
      p.tags?.some((t) => t.toLowerCase().includes(q.toLowerCase())),
  )

  if (!matched.some((p) => p.name === q)) {
    const customSearchPlace: Omit<Place, 'id' | 'order'> = {
      name: q,
      category: '네이버 지도 검색 장소',
      cost: 0,
      costLabel: '입장료/비용 개별 확인',
      walkMinutes: 10,
      reason: `사용자께서 직접 검색하여 추가하신 필수 방문지 '${q}'입니다.`,
      isMustVisit: true,
      mapX: Math.floor(Math.random() * 40) + 30,
      mapY: Math.floor(Math.random() * 40) + 30,
      address: `전북 전주시 완산구 ${q} 부근 (네이버 지도 검색)`,
      operatingHours: '운영시간 개별 확인',
      phone: '네이버 지도 참조',
      tags: ['#직접검색추가', '#필수방문지', '#네이버지도'],
      suggestedDuration: '45분',
      tips: `💡 현지인 팁: 네이버 지도를 통해 '${q}'의 최신 휴무일과 실시간 방문 후기를 확인하세요.`,
      naverMapUrl: `https://map.naver.com/v5/search/${encodeURIComponent(q)}`,
      transitInfo: `🚌 시내버스 검색: 네이버 지도를 통해 '${q}'행 시내버스 노선을 확인해 주세요.`,
      parkingInfo: `🚗 주차장: '${q}' 인근 공영/민영 주차장 안내를 참조하세요.`,
    }
    return NextResponse.json([customSearchPlace, ...matched].slice(0, 8))
  }

  return NextResponse.json(matched.slice(0, 8))
}
